// Writes the wall lanes (D056, "Every wall stands on a pirate path") from the sim's own rules
// (src/pirates/wall-lanes.js deriveWallLanes) into the two copies the game reads:
//   frontend/src/island/wall-lanes.js        the Move preview and the battle guide (browser)
//   backend/content/island_layout.json       "wallLanes", the server's placement rule (layout.py)
// Run it after a change to the boarders' routes (sim.js lanes, coast, heart, boarder-paths.js), then commit both.
// tests/pirates/wall-lanes.test.js fails until the two copies equal the derivation again.
//
//   node scripts/derive-wall-lanes.mjs [--check]     --check: only compare, exit 1 when a copy is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';

registerHooks({
  load(url, context, nextLoad) {
    if (url.endsWith('.json')) return nextLoad(url, { ...context, importAttributes: { type: 'json' } });
    return nextLoad(url, context);
  },
});
const { deriveWallLanes } = await import('../src/pirates/wall-lanes.js');

const FRONT = new URL('../src/island/wall-lanes.js', import.meta.url);
const BACK = new URL('../../backend/content/island_layout.json', import.meta.url);
const rows = deriveWallLanes();
const lines = rows.map(row => `  [${row.join(', ')}],`).join('\n');
const front = `// The wall lanes (D056, "Every wall stands on a pirate path"): the build-grid cells where a wall, even standing
// alone, stops boarders on their way from a landing to the heart. GENERATED by scripts/derive-wall-lanes.mjs from
// src/pirates/wall-lanes.js; do not edit by hand. The server keeps the same rows in backend/content/island_layout.json.
//   rows: [z, x0, x1, x0, x1, …]: on row z, a wall may be centred on every half unit from x0 to x1.
export const WALL_LANE_ROWS = Object.freeze([
${lines}
].map(row => Object.freeze(row)));
`;
const block = `  "wallLanes": {"about": "D056: where a wall may stand (its centre), as rows [z, x0, x1, ...]: every half unit from x0 to x1 on row z. Generated by frontend/scripts/derive-wall-lanes.mjs; do not edit by hand.", "rows": [\n${rows.map(row => `    [${row.join(', ')}]`).join(',\n')}\n  ]},\n`;
const json = readFileSync(BACK, 'utf8');
const at = json.indexOf('  "wallLanes":');
const keep = json.search(/^  "(?:wallPerimeter|wallObstacles|keepOut)":/m);
const back = at >= 0 ? json.slice(0, at) + block + json.slice(keep) : json.slice(0, keep) + block + json.slice(keep);
JSON.parse(back); // still one valid file

if (process.argv.includes('--check')) {
  let stale = [];
  try { if (readFileSync(FRONT, 'utf8') !== front) stale.push('src/island/wall-lanes.js'); } catch { stale.push('src/island/wall-lanes.js'); }
  if (json !== back) stale.push('backend/content/island_layout.json');
  console.log(stale.length ? `out of date: ${stale.join(', ')}` : `wall lanes up to date (${rows.length} rows)`);
  process.exitCode = stale.length ? 1 : 0;
} else {
  writeFileSync(FRONT, front); writeFileSync(BACK, back);
  console.log(`wrote ${rows.length} rows of wall lanes`);
}
