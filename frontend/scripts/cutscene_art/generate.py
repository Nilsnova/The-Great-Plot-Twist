"""Draw the G29 cutscene art and title parallax planes. Authoring only: Python 3.9+, Pillow and NumPy.

From frontend/: python3 scripts/cutscene_art/generate.py [--contact-sheet PATH]

Writes lossless WebP files to public/cutscenes/ (each native pixel enlarged 4x) and regenerates the
id -> path registry in src/cutscenes/art.js. Every image is original and code-drawn.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from PIL import Image, ImageDraw, ImageFont  # noqa: E402

from paint import SCALE  # noqa: E402
from scenes import H, SCENES, TITLE_LAMP, TITLE_LAYERS, TITLE_W, W  # noqa: E402

ROOT = HERE.parents[1]
OUT = ROOT / "public" / "cutscenes"
REGISTRY = ROOT / "src" / "cutscenes" / "art.js"
BUDGET = 1_500_000


def save(image: Image.Image, name: str) -> dict:
    path = OUT / f"{name}.webp"
    image.save(path, "WEBP", lossless=True, quality=100, method=6, exact=image.mode == "RGBA")
    data = path.read_bytes()
    return {"file": f"cutscenes/{name}.webp", "width": image.width, "height": image.height,
            "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


def contact_sheet(images: dict, layers: list, records: dict, path: Path) -> None:
    thumb_w, thumb_h, pad, label = 640, 360, 16, 22
    font = ImageFont.load_default(size=16)
    cols = 2
    tiles = [(name, img) for name, img in images.items()]
    composite = Image.new("RGBA", layers[0][1].size)
    for _, img, _ in layers:
        composite.alpha_composite(img.convert("RGBA"))
    composite = composite.crop((0, 0, W * SCALE, H * SCALE))
    tiles.append(("title (all layers)", composite))
    checker = Image.new("RGBA", (TITLE_W * SCALE, H * SCALE), "#7a7f8c")
    cd = ImageDraw.Draw(checker)
    for y in range(0, checker.height, 32):
        for x in range(0, checker.width, 32):
            if (x // 32 + y // 32) % 2:
                cd.rectangle((x, y, x + 31, y + 31), fill="#9aa0ac")
    for name, img, _ in layers:
        tile = checker.copy()
        tile.alpha_composite(img.convert("RGBA"))
        tiles.append((f"title-{name}", tile))
    rows = (len(tiles) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * (thumb_w + pad) + pad, rows * (thumb_h + label + pad) + pad + 30), "#14161c")
    draw = ImageDraw.Draw(sheet)
    total = sum(r["bytes"] for r in records.values())
    draw.text((pad, 8), f"G29 cutscene art - {len(records)} files, {total:,} bytes (budget {BUDGET:,})",
              fill="#e8e8e8", font=font)
    for i, (name, img) in enumerate(tiles):
        x = pad + (i % cols) * (thumb_w + pad)
        y = 30 + pad + (i // cols) * (thumb_h + label + pad)
        fitted = img.convert("RGB").resize((thumb_w, round(thumb_w * img.height / img.width)), Image.Resampling.NEAREST)
        sheet.paste(fitted.crop((0, 0, thumb_w, min(thumb_h, fitted.height))), (x, y + label))
        record = records.get(name)
        caption = name if record is None else f"{name}  {record['width']}x{record['height']}  {record['bytes']:,} B"
        draw.text((x, y), caption, fill="#e8e8e8", font=font)
    path.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(path, optimize=True)


def write_registry(records: dict, layers: list) -> None:
    scenes = {name: records[name] for name in SCENES}
    layer_list = [{"id": name, "depth": depth, **{k: records[f"title-{name}"][k] for k in ("file", "width", "height", "bytes")}}
                  for name, _, depth in layers]
    lines = [
        "// Generated by scripts/cutscene_art/generate.py - do not edit by hand; rerun the script.",
        "// Original code-drawn cutscene art (credited in ASSETS.md). Paths are relative to the site root,",
        "// like other public/ assets. Lazy-load these only when a cutscene or the animated title needs",
        "// them; none of them belongs to the cold title load.",
        f"export const CUTSCENE_PIXEL_SCALE = {SCALE};",
        "",
        "/** Full-frame cutscene backdrops, keyed by scene id. */",
        "export const cutsceneArt = Object.freeze({",
    ]
    for name, r in scenes.items():
        lines.append(f"  '{name}': Object.freeze({{file: '{r['file']}', width: {r['width']}, height: {r['height']}, "
                     f"bytes: {r['bytes']}}}),")
    lines += [
        "});",
        "",
        "/**",
        " * Title backdrop planes, back to front. Each is wider than 16:9 so it can drift horizontally;",
        " * depth is a suggested parallax factor (0 = fixed sky, 1 = moves with the foreground).",
        " * Every layer except the sky is transparent.",
        " */",
        "export const titleLayers = Object.freeze([",
    ]
    for layer in layer_list:
        lines.append(f"  Object.freeze({{id: '{layer['id']}', file: '{layer['file']}', depth: {layer['depth']}, "
                     f"width: {layer['width']}, height: {layer['height']}, bytes: {layer['bytes']}}}),")
    lamp = {"x": round(TITLE_LAMP["x"] * SCALE), "y": round(TITLE_LAMP["y"] * SCALE)}
    lines += [
        "]);",
        "",
        "/** Lantern centre in the lighthouse layer's pixels: the origin for an animated beam. */",
        f"export const titleLampOrigin = Object.freeze({{layer: 'lighthouse', x: {lamp['x']}, y: {lamp['y']}}});",
        "",
        "/** Path for a scene id or title layer id; throws on unknown ids so typos fail loudly. */",
        "export function cutscenePath(id) {",
        "  if (Object.hasOwn(cutsceneArt, id)) return cutsceneArt[id].file;",
        "  const layer = titleLayers.find(item => item.id === id);",
        "  if (layer) return layer.file;",
        "  throw new Error(`Unknown cutscene art ${id}`);",
        "}",
        "",
    ]
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--contact-sheet", type=Path, help="also write a PNG contact sheet here")
    args = parser.parse_args(argv)
    OUT.mkdir(parents=True, exist_ok=True)
    records, images = {}, {}
    for name, painter in SCENES.items():
        image = painter().finish(colors=56)
        images[name] = image
        records[name] = save(image, name)
    layers = []
    for name, painter, depth in TITLE_LAYERS:
        canvas = painter()
        image = canvas.finish(colors=48 if canvas.opaque else 32)
        layers.append((name, image, depth))
        records[f"title-{name}"] = save(image, f"title-{name}")
    total = sum(r["bytes"] for r in records.values())
    manifest = {"source": "scripts/cutscene_art/generate.py", "scale": SCALE, "totalBytes": total, "files": records}
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    write_registry(records, layers)
    for name, r in records.items():
        print(f"{r['file']:<36} {r['width']}x{r['height']}  {r['bytes']:>8,} B")
    print(f"total {total:,} bytes (budget {BUDGET:,})")
    if args.contact_sheet:
        contact_sheet(images, layers, records, args.contact_sheet)
        print(f"contact sheet: {args.contact_sheet}")
    return 0 if total <= BUDGET else 1


if __name__ == "__main__":
    sys.exit(main())
